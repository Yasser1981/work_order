"""جسرٌ بين الاسم المعروض ومفتاح سعره في الكتالوج (ق-٧٧، ق-٧٨).

بعض البنود تُعرض باسم غير الاسم الذي تحمله نسخة الأسعار: «تسليك سلك ألمنيوم
120/20 ملم²» يُعرض، و«تسليك شبكة الضغط العالي» هو مفتاح سعره. والسبب أن **تغيير
المفتاح كان سيكسر كل نسخة أسعار محفوظة**: المحرك يطلب الأجر باسمه، ونسخة آب لا
تعرف الاسم الجديد.

فهذه الوحدة تجمع الخرائط من كل وحدات المحرك في **مصدر واحد** يقرأ منه من يحتاج
الترجمة — وأوّلهم حارس التغطية. ولولا الجمع هنا لكان على كل قارئ أن يعرف
الوحدات التي فيها استثناءات، فتُنسى واحدة يوماً ويصير بندٌ بلا سعر بلا تنبيه.
"""

from __future__ import annotations

from .lowvoltage import RATE_KEYS as _LOW_VOLTAGE
from .overhead import RATE_KEYS as _OVERHEAD

RATE_KEYS: dict[str, str] = {**_OVERHEAD, **_LOW_VOLTAGE}
"""الاسم المعروض ← مفتاح سعره في الكتالوج، لكل بند يختلف فيه الاثنان."""


def rate_key(name: str) -> str:
    """مفتاح سعر البند في الكتالوج — نفسُ اسمه ما لم يكن له استثناء مسجَّل."""
    return RATE_KEYS.get(name, name)
