# -*- coding: utf-8 -*-
"""المواد غير المتوفرة في المخازن — تأشيرٌ يدوي وكلفةٌ محسوبة (ق-٧٦).

بنصّ المستخدم: «كلفة المواد غير المتوفرة تحسب يدوياً. يعني ضع إمكانية لتأشير
المواد غير المتوفرة في المخازن وأنا اختارها ليتم حساب مجموع كلفها من قبل
البرنامج».

فالاختيار وحده يدويّ، **والجمع آليّ** — وهو الفصل الصحيح: البرنامج لا يعرف ما
في المخازن، والمستخدم لا ينبغي أن يجمع أعمدة بيده.

## قاعدتان تحكمان هذا الملف

**١. المواد التي كلفتها ضمن الأجور متوفرة دائماً.** بنصّ المستخدم: «هذه المواد
تعتبر متوفرة دائماً… (الكونكريت مع الأعمدة) و(الشتايكر والرمل وشريط التحذير مع
القابلوات الأرضية)». فتأشيرها ممنوع في الواجهة، ولو ورد اسمها في ملف قديم
أُهمل وأُبلغ عنه — ولم يُضف صفرٌ صامت إلى كلفة غير المتوفرة.

**٢. المادة غير المُسعَّرة تُحسب صفراً — فيجب أن يُنبَّه عليها.** فلو أشّرها
المستخدم وهي بلا سعر، ظهرت في قائمة الفقرات ولم تزد المجموع شيئاً. وهذا فرقٌ
لا يراه أحد في الورقة، فيُبلَّغ عنه في الواجهة قبل الطباعة.
"""

from __future__ import annotations


def unavailable_summary(materials: list[dict], names) -> dict:
    """خلاصة المواد المؤشَّرة «غير متوفرة» في جدول مواد بعينه.

    `materials` قائمة صفوف جدول المواد **كما ستُطبع** — فترقيم الفقرات هنا هو
    الترقيم نفسه الذي يقرأه المدقّق في الورقة. ولو رُقّمت من قائمة أخرى لأشار
    السطر إلى فقرات لا تقابل ما أُشّر.

    ويعيد:

    | المفتاح | معناه |
    |---|---|
    | `فقرات` | أرقام الفقرات المؤشَّرة بترتيب الجدول |
    | `الكلفة` | مجموع كلفها |
    | `أسماء` | أسماء المواد المؤشَّرة |
    | `بلا_سعر` | المؤشَّرة التي لا سعر لها — تُحسب صفراً فيُنبَّه عليها |
    | `متوفرة_دائماً` | المؤشَّرة التي كلفتها ضمن الأجور — تُهمَل |
    """
    wanted = set(names or ())
    numbers: list[int] = []
    chosen: list[str] = []
    unpriced: list[str] = []
    always: list[str] = []
    cost = 0.0

    for index, row in enumerate(materials, start=1):
        if row["المادة"] not in wanted:
            continue
        if row["كمية_فقط"]:
            always.append(row["المادة"])
            continue
        numbers.append(index)
        chosen.append(row["المادة"])
        if row["سعر_مفقود"]:
            unpriced.append(row["المادة"])
            continue
        cost += row["الكلفة"]

    return {
        "فقرات": numbers,
        "الكلفة": cost,
        "أسماء": chosen,
        "بلا_سعر": unpriced,
        "متوفرة_دائماً": always,
    }


def selectable(row: dict) -> bool:
    """هل يجوز تأشير هذه المادة «غير متوفرة»؟

    المادة التي كلفتها ضمن الأجور لا تُؤشَّر (القاعدة ١ أعلاه). وتُفصَل في دالة
    مستقلّة كي تقرأها الواجهة والخلاصة من مصدر واحد، فلا يفترقان.
    """
    return not row["كمية_فقط"]
