# -*- coding: utf-8 -*-
"""الرابط بين كمية المادة وكمية أجرها (ق-٨١).

**العلّة التي يعالجها،** بنصّ المستخدم: «قالب الإيزو لا يحتوي على فقرات تخص
العمل. فعندما أغيّر مثلاً كمية الأسلاك، سوف يغيّر القالب سعر المادة فقط، لكن لا
يغيّر فقرة العمل الخاصة بالأسلاك».

فكمية بند الأجر في ملف الإكسل كانت رقماً جامداً لا يعرف شيئاً عن كمية مادته.
وتعديل السلك يُحدّث كلفة السلك ولا يمسّ أجر التسليك — فتخرج ورقةٌ نصفها معدَّل.

## القاعدة: إعلانٌ في المحرك، لا استنتاج من الأرقام

كل بند أجر يُعلن `driver` — أي (اسم المادة، وحدتها) التي تقود كميته. والربط
**لا يُستنتج من تطابق الأرقام**: في مشروع حقيقي كانت كمية «عبور الشوارع
الفرعية» 24 وكمية «ترمنل 50 ملم²» 24 كذلك، **مصادفةً محضة**. فالربط بالأرقام
كان سيجعل تعديل الترمنلات يغيّر أجر عبور الشوارع.

## ولا يُربط إلا عند التطابق التامّ

حتى مع الإعلان، لا يُقبل الربط إلا إذا كانت الكميتان **متساويتين فعلاً** في هذه
النتيجة بعينها. فبعض الحالات تُفرّقهما بحقّ:

| الحالة | لماذا تختلف الكميتان |
|---|---|
| تقريب الأمتار | المواد بالمتر تُقرَّب لأعلى (ق-٥٦)، والأجر يُدفع على الفعلي |
| مادة واحدة لبندَي أجر | الفاصل ON-LOAD مادةٌ واحدة وأجران (منتصف ورأس قابلو) |
| بندُ أجرٍ من مادتين | صندوق النهاية: داخلي وخارجي في بندِ أجرٍ واحد |

وفي هذه الحالات تبقى الكمية **رقماً جامداً** في الإكسل ولا تُربط — لأن الربط
حينها يغيّر رقماً، والأرقام لا تتغيّر إلا بأمر (ق-٠).
"""

from __future__ import annotations


def driver_keys(line) -> tuple:
    """مفاتيحُ الموادّ التي يُعلن هذا البند أنها تقود كميته — صفرٌ أو أكثر.

    يوحّد الحقلين: `driver` لمادةٍ واحدة و`drivers` لعدّة مواد (ق-٩١). فيقرأ
    مَن بعده مفاتيحَ في كل الحالات، ولا يعرف أيّ الحقلين كُتب.
    """
    if line.drivers:
        return tuple(line.drivers)
    return (line.driver,) if line.driver else ()


def material_drivers(result: dict) -> dict[int, tuple]:
    """فهرس بند الأجر ← **مفاتيح** المواد التي تقوده، حين يصحّ الربط.

    المفتاح (اسم، وحدة) لا رقم سطر: أرقام السطور تخصّ كل ورقة على حدة، والمفتاح
    واحد في كل مكان.

    **والقيمة تُبّةٌ دائماً** ولو كانت مادةً واحدة (ق-٩١) — فيكتب القارئ معادلة
    جمعٍ بلا أن يفرّق بين حالةٍ وحالة.

    **ولا يصحّ الربط إلا بتطابق المجموع:** مجموعُ كميات الموادّ المُعلَنة يساوي
    كمية البند. وهو تعميمُ شرط ق-٨١ لا تخفيفُه: المادة الواحدة حالةٌ خاصّة من
    المجموع. فلو نقصت مادةٌ من النتيجة أو اختلف رقمٌ، بقيت الكمية جامدة ولم
    يتغيّر رقمٌ بلا أمر (ق-٠).
    """
    materials = {(row["المادة"], row["الوحدة"]): row for row in result["المواد"]}
    links: dict[int, tuple] = {}
    for index, line in enumerate(result["أجور_العمل"]):
        keys = driver_keys(line)
        rows = [materials.get(key) for key in keys]
        if keys and all(row is not None for row in rows):
            if sum(row["الكمية"] for row in rows) == line.qty:
                links[index] = keys
    return links


def unlinked_drivers(result: dict) -> list[tuple[str, str]]:
    """بنود أعلنت مادةً تقودها ولم يصحّ ربطها — للتشخيص والحراسة.

    تعيد (اسم البند، سبب عدم الربط). وجودها ليس خطأً بالضرورة (انظر الجدول
    أعلاه)، لكن **نموّها فجأةً** علامةُ خللٍ يستحقّ النظر.
    """
    materials = {(row["المادة"], row["الوحدة"]): row for row in result["المواد"]}
    out = []
    for line in result["أجور_العمل"]:
        keys = driver_keys(line)
        if not keys:
            continue
        missing = [key for key in keys if key not in materials]
        if missing:
            out.append((line.name,
                        f"لا مادة باسم «{missing[0][0]}» في هذه النتيجة"))
            continue
        total = sum(materials[key]["الكمية"] for key in keys)
        if total != line.qty:
            out.append((line.name, f"الكمية {line.qty:g} والمادة {total:g}"))
    return out
