# -*- coding: utf-8 -*-
"""يشغّل المحرك المتحقَّق منه بمدخلات 33 ك.ف مملوءة، تحت الحالتين، ويقارن."""
import math, openpyxl
def rup(x,d=0):
    m=10**d; return math.ceil(round(x*m,9))/m

wb=openpyxl.load_workbook('wo.xlsx',data_only=True)
wsm=wb['جدول_المواد']
NAMES={r:(wsm.cell(r,2).value, wsm.cell(r,3).value, wsm.cell(r,5).value or 0) for r in range(2,63)}

def run(b25):
    I={'B2':0,'B3':0,'B4':0,'B5':0,'B6':0,'B7':0,'B8':0,'B9':0,'B10':0,'B11':0,
       'B12':'أسلاك','B13':0,'B14':0,'B15':0,'B16':0,'B17':0,'B18':0,'B19':0,
       'B20':0,'B21':0,'B22':0,'B23':0,'B24':0,
       'B25':b25,
       'B26':2000,   # طول المسار الهوائي 33 ك.ف
       'B27':300,    # طول القابلو الأرضي 33 ك.ف
       'B28':30,     # عمود 14م تعليق
       'B29':3,      # ركيزة شد وسطية
       'B30':2,      # ركيزة بداية ونهاية
       'B31':2,'B32':1,'B33':1,'B34':1,
       'B78':'لا','B79':'قابلو مبروم','B80':0,'B81':0,
       'D60':0,'F63':0,'F64':0,'D73':300}
    d = b25=='مزدوجة'; s = b25=='مفردة'
    I['I25']=rup(I['B6']*1 + I['B7']*0.756 + I['B9']*0.45 + I['B8']*0.63)
    conc=[I['B28']*2.76 if d else 0, I['B28']*1.56 if s else 0,
          I['B29']*10.31 if d else 0, I['B29']*10.31 if s else 0,
          I['B30']*18.76 if d else 0, I['B30']*12.26 if s else 0]
    I['I40']=rup(sum(conc))
    RAW=[]
    def add(n,u,q): RAW.append((n,u,q))
    add('كونكريت أساسات الأعمدة','متر مكعب', I['I25']+I['I40'])
    add('سلك ألمنيوم 210/35 ملم²','متر', I['B26']*6*1.1 if d else I['B26']*3*1.1)
    c78=I['B28']+I['B29']*2+I['B30']*2
    add('عمود مشبك 14م','عدد', c78)
    c79=I['B28']*3 if d else I['B28']*1
    add('براكيت 2 متر','عدد', c79)
    add('براكيت 2.5 متر','عدد', I['B29']*3+I['B30']*3)
    add('عازل قرصي 33 ك.ف مع الملحقات','سيت', (I['B29']+I['B30'])*12)
    add('عازل دبوسي 33 ك.ف مع السبندل','عدد', c78*3+c79*2)  # فرع «مفردة» دائماً (خطأ B30)
    add('سلك نحاس 50 ملم2','متر', c78*1.5)
    add('ترمنل 50 ملم²','عدد', c78*1)
    c85=I['B34']; add('فاصل هوائي 33 ك.ف','عدد', c85)
    add('مانعة صواعق 33 ك.ف','سيت', c85)
    add('قاعدة مانعة صواعق مع الملحقات','عدد', c85)
    add('قضيب تأريض 1.5 متر مع القفيص','عدد', c85)
    add('قابلو 1×185 ملم2','متر', c85*20)
    add('ترمنل 185 ملم2','عدد', c85*6)
    add('قابلو نحاس 1×50 ملم²','متر', c85*15)
    add('ترمنل 50 ملم²','عدد', c85*1)
    add('معدات المنيوم - المنيوم 210 ملم2','عدد', (I['B29']+I['B30'])*24)
    add('شتايكر 50×50×5 سم','عدد', rup((I['D73']/0.5)*2) if d else rup(I['D73']/0.5))
    add('رمل نهري','متر مكعب', rup(I['D73']*0.4*1.2 if d else I['D73']*0.4*0.6))
    add('شريط تحذير','لفة', rup(I['D73']/90))
    add('قابلو 1×400 ملم2 جهد 33 ك.ف','متر', I['B27'])
    add('صندوق مستقيم 1×400 ملم2 جهد 33 ك.ف','عدد', I['B31'])
    add('صندوق نهاية داخلي 1×400 ملم2 جهد 33 ك.ف','سيت', I['B32'])
    add('صندوق نهاية خارجي 1×400 ملم2 جهد 33 ك.ف','سيت', I['B33'])
    add('شيش تسليح','طن', ((I['B29']*4)+(I['B30']*6))/130)
    def sf(n,u): return sum(q for a,b,q in RAW if a==n and b==u)
    qty={}; mat_total=0
    for r,(n,u,p) in NAMES.items():
        q=sf(n,u); qty[r]=q; mat_total+=q*p
    lab=[('نصب 14م مزدوج',I['B28'] if d else 0,450000),
         ('ركيزة وسطية مزدوج',I['B29'] if d else 0,2075000),
         ('ركيزة بداية/نهاية مزدوج',I['B30'] if d else 0,3250000),
         ('نصب 14م مفرد',I['B28'] if s else 0,260000),
         ('ركيزة وسطية مفرد',I['B29'] if s else 0,2050000),
         ('ركيزة بداية/نهاية مفرد',I['B30'] if s else 0,2200000),
         ('تسليك 33',qty[48],850),('نصب فاصل 33',qty[54],90000),
         ('مد قابلو 33',qty[59],2000),
         ('صندوق مستقيم 33',qty[60],75000),
         ('صندوق نهاية 33',qty[61]+qty[62],225000)]
    lab_total=sum(q*p for _,q,p in lab)
    extra={'شيش تسليح (غير مُسعّر)':sf('شيش تسليح','طن')}
    return qty, mat_total, lab_total, dict(lab and {k:(q,p) for k,q,p in lab}), extra

qs,ms,ls,labs,es = run('مفردة')
qd,md,ld,labd,ed = run('مزدوجة')

print('المدخلات: مسار هوائي 2000م | قابلو أرضي 300م | 30 عمود تعليق | 3 ركيزة وسطية | 2 ركيزة بداية/نهاية')
print()
print('=== الكميات: هل تتغيّر بتغيير B25؟ ===')
print(f'{"المادة":<42}{"مفردة":>12}{"مزدوجة":>12}   الحالة')
print('-'*82)
changed=unchanged=0
for r,(n,u,p) in sorted(NAMES.items()):
    a,b=qs[r],qd[r]
    if a==0 and b==0: continue
    if a!=b:
        st='✅ يتغيّر'; changed+=1
    else:
        st='⚠️  ثابت'; unchanged+=1
    print(f'{n[:42]:<42}{a:>12,.2f}{b:>12,.2f}   {st}')
print('-'*82)
print(f'يتغيّر: {changed} مادة   |   ثابت: {unchanged} مادة')
print()
print('=== الأجور ===')
for k in labs:
    a=labs[k][0]*labs[k][1]; b=labd[k][0]*labd[k][1]
    if a or b:
        print(f'  {k:<32}{a:>14,.0f}{b:>14,.0f}   {"✅" if a!=b else "⚠️ ثابت"}')
print()
print('=== المجاميع ===')
print(f'  كلفة المواد : مفردة {ms:>14,.0f}   مزدوجة {md:>14,.0f}   فرق {md-ms:>+14,.0f}')
print(f'  أجور العمل  : مفردة {ls:>14,.0f}   مزدوجة {ld:>14,.0f}   فرق {ld-ls:>+14,.0f}')
print(f'  الكلي       : مفردة {ms+ls:>14,.0f}   مزدوجة {md+ld:>14,.0f}   فرق {md+ld-ms-ls:>+14,.0f}')
print()
print('=== كميات لا يظهرها جدول المواد ===')
print(f'  شيش تسليح: مفردة {es["شيش تسليح (غير مُسعّر)"]:.3f} طن | مزدوجة {ed["شيش تسليح (غير مُسعّر)"]:.3f} طن  ← لا صف له في جدول المواد')
